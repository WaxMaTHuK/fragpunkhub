export async function seedLancerCatalog(): Promise<{ created: number; skipped: number }> {
  const existing = new Set((await listPosts(true))
    .filter((post) => post.type === "lancer")
    .map((post) => post.title.trim().toLocaleLowerCase("ru-RU")));
  let created = 0;
  for (const [index, lancer] of LANCERS.entries()) {
    if (existing.has(lancer.title.toLocaleLowerCase("ru-RU"))) continue;
    await savePost({
      type: "lancer", title: lancer.title, summary: lancer.summary,
      content: lancer.content, readTime: "2 мин", accent: lancer.accent,
      published: true, sortOrder: 600 + index,
    }, "site-owner");
    created++;
  }
  return { created, skipped: LANCERS.length - created };
}
