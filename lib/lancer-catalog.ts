export async function seedLancerCatalog(): Promise<{ created: number; skipped: number }> {
  const existing = new Set((await listPosts(true))
    .filter((post) => post.type === "lancer")
    .map((post) => post.title.trim().toLocaleLowerCase("ru-RU")));
  let created = 0;
  let skipped = 0;
  for (const lancer of LANCERS) {
    if (existing.has(lancer.title.toLocaleLowerCase("ru-RU"))) {
      skipped++;
      continue;
    }
    await savePost({ type: "lancer", title: lancer.title, summary: lancer.summary,
      content: lancer.content, readTime: "3 мин", accent: lancer.accent,
      published: true, sortOrder: lancer.sortOrder }, "site-owner");
    created++;
  }
  return { created, skipped };
}
